const dicts: Record<Lang, Dict> = { ar, en };
export type TKey = keyof Dict;

export function useT() {
  const lang = useSettings((s) => s.lang);
  const d = dicts[lang];
  return { t: (k: TKey) => d[k], lang, dir: lang === "ar" ? ("rtl" as const) : ("ltr" as const) };
}

export function localeFor(lang: Lang) {
  return lang === "ar" ? "ar-EG-u-nu-latn" : "en-US";
}

export function formatTime12(d: Date, lang: Lang) {
  const h = d.getHours();
  const m = String(d.getMinutes()).padStart(2, "0");
  return { hm: `${h % 12 || 12}:${m}`, period: h < 12 ? dicts[lang].am : dicts[lang].pm };
}

export function formatHM24(d: Date) {
  return `${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`;
}
